export function guardarSesionUsuario(authResponse) {
  const userData = [{ ...authResponse[0] }]
  const rawMenu = authResponse[0].menu || []
  const modulo = authResponse[0].modulo || 'cm'
  const idusuario = authResponse[0].idusuario || ''

  const menuTransformado = rawMenu.map((item) => ({
    usuario: idusuario,
    titulo: item.titulo,
    codigo: item.codigo,
    submenu: (item.submenu || []).map((sub) => ({
      ...sub,
      codigo: sub.codigo ? `${sub.codigo.split('-')[0]}-${idusuario}` : sub.codigo,
    })),
  }))

  const userMenu = [{ modulo, menu: menuTransformado }]

  delete userData[0].menu

  localStorage.setItem('mistersofts-cm', JSON.stringify(userData))
  localStorage.setItem('mistersofts-cmmenu', JSON.stringify(userMenu))
  localStorage.setItem('puedeIniciarsesion', 'true')
  if (!localStorage.getItem('mistersofts-cm-confi-conta')) {
    localStorage.setItem('mistersofts-cm-confi-conta', JSON.stringify([]))
  }
  sessionStorage.removeItem('logoutIntencional')

  return { userData, userMenu }
}
